import { test, expect } from "bun:test";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";

test("external SQL enforces the entire applicant journey and authorization", async () => {
  const db = new PGlite();
  const employee='11111111-1111-4111-8111-111111111111';
  const admin='22222222-2222-4222-8222-222222222222';
  const application='33333333-3333-4333-8333-333333333333';
  const template='44444444-4444-4444-8444-444444444444';
  await db.exec(`
    CREATE ROLE authenticated; CREATE ROLE anon; CREATE ROLE service_role; CREATE ROLE authenticator;
    CREATE SCHEMA auth; CREATE SCHEMA storage;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
    CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT current_setting('test.role',true) $$;
    CREATE FUNCTION public.has_role(u uuid,r text) RETURNS boolean LANGUAGE sql AS $$ SELECT u='${admin}'::uuid AND r='admin' $$;
    CREATE TABLE public.profiles(id uuid PRIMARY KEY,email text,first_name text,last_name text,phone text,birth_date date,street text,postal_code text,city text,employment_type text,start_date date,account_holder text,iban text,bic text,verified boolean,resource_assignment_approved boolean);
    CREATE TABLE public.applications(id uuid PRIMARY KEY,first_name text,last_name text,email text,phone text,birth_date date,status text,employment_type text,reviewed_by uuid,reviewed_at timestamptz);
    CREATE TABLE public.contract_templates(id uuid PRIMARY KEY,name text,category text,version text,content text,is_active boolean);
    CREATE TABLE public.employee_documents(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,document_type text,title text,content text,contract_type text,start_date text,signature_data text);
    CREATE TABLE public.company_signature(signature_data text,updated_at timestamptz);
    CREATE TABLE public.tasks(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),assigned_to uuid); ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
    CREATE TABLE public.task_submissions(id uuid PRIMARY KEY DEFAULT gen_random_uuid()); ALTER TABLE public.task_submissions ENABLE ROW LEVEL SECURITY;
    CREATE TABLE storage.objects(bucket_id text,name text); ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
    GRANT USAGE ON SCHEMA public,auth,storage TO authenticated,anon,service_role;
    GRANT SELECT,UPDATE ON public.profiles,public.employee_documents TO authenticated;
    CREATE POLICY employee_document_access ON public.employee_documents FOR ALL TO authenticated USING(true) WITH CHECK(true);
    INSERT INTO public.profiles(id,email) VALUES('${employee}','worker@example.test');
    INSERT INTO public.applications(id,first_name,last_name,email,status) VALUES('${application}','Max','Muster','worker@example.test','pending');
    INSERT INTO public.contract_templates VALUES('${template}','Teilzeit','Teilzeit','1','Vertrag {{first_name}} {{last_name}} {{gehalt}} {{startdatum}}',true);
    SELECT set_config('test.role','service_role',false),set_config('test.uid','${admin}',false);
  `);
  await db.exec(readFileSync(new URL('../selfhost/bewerberaufnahme.sql', import.meta.url),'utf8'));
  const legacy = await db.query<{allowed:boolean}>(`SELECT public.applicant_is_active('${employee}') AS allowed`);
  expect(legacy.rows[0]?.allowed).toBe(true);
  const key='a'.repeat(64);
  for(let i=0;i<5;i++) expect((await db.query<{allowed:boolean}>(`SELECT public.applicant_submission_allowed('${key}') AS allowed`)).rows[0]?.allowed).toBe(true);
  expect((await db.query<{allowed:boolean}>(`SELECT public.applicant_submission_allowed('${key}') AS allowed`)).rows[0]?.allowed).toBe(false);
  await db.exec(`INSERT INTO public.applicant_submission_limits(key,attempts) VALUES('${'b'.repeat(64)}',99)`);
  expect((await db.query<{allowed:boolean}>(`SELECT public.applicant_global_submission_allowed('${'b'.repeat(64)}') AS allowed`)).rows[0]?.allowed).toBe(true);
  expect((await db.query<{allowed:boolean}>(`SELECT public.applicant_global_submission_allowed('${'b'.repeat(64)}') AS allowed`)).rows[0]?.allowed).toBe(false);
  await db.exec(`SELECT public.applicant_finalize_acceptance('${application}','${employee}','${template}','2026-11-01',2200,'${admin}');`);
  const count=async()=>Number((await db.query<{count:number}>(`SELECT count(*)::integer AS count FROM public.employee_documents`)).rows[0]?.count);
  expect(await count()).toBe(1);
  await db.exec(`SELECT public.applicant_finalize_acceptance('${application}','${employee}','${template}','2026-11-01',2200,'${admin}');`);
  expect(await count()).toBe(1);
  await db.exec(`SELECT set_config('test.role','authenticated',false),set_config('test.uid','${employee}',false);`);
  const active=async()=> (await db.query<{active:boolean}>('SELECT active FROM public.applicant_workflows')).rows[0]?.active;
  expect(await active()).toBe(false);
  await expect(db.exec(`SELECT public.save_applicant_bank('Max Muster','DE89370400440532013000','COBADEFFXXX')`)).rejects.toThrow('Sign the contract first');
  await expect(db.exec(`INSERT INTO public.tasks(assigned_to) VALUES('${employee}')`)).rejects.toThrow('Mitarbeiter noch nicht aktiv');
  const signature='data:image/png;base64,'+'A'.repeat(240);
  await db.exec(`SELECT public.sign_applicant_contract('${signature}')`);
  await expect(db.exec(`SELECT public.sign_applicant_contract('${signature}')`)).rejects.toThrow('Already signed');
  expect(await active()).toBe(false);
  await expect(db.exec(`SELECT public.save_applicant_bank('Max Muster','DE89370400440532013001','COBADEFFXXX')`)).rejects.toThrow('Invalid IBAN checksum');
  await db.exec(`SELECT public.save_applicant_bank('Max Muster','DE89370400440532013000','COBADEFFXXX')`);
  expect(await active()).toBe(false);
  const front=employee+'/applicant/front',back=employee+'/applicant/back';
  await db.exec(`INSERT INTO storage.objects VALUES('verification-documents','${front}'),('verification-documents','${back}');`);
  await expect(db.exec(`SELECT public.submit_applicant_identity('${front}','${front}')`)).rejects.toThrow('Both identity images required');
  await db.exec(`SELECT public.submit_applicant_identity('${front}','${back}')`);
  expect(await active()).toBe(false);
  await expect(db.exec(`SELECT public.review_applicant_identity('${employee}',true,NULL)`)).rejects.toThrow('Admin required');
  await db.exec(`SELECT set_config('test.uid','${admin}',false);`);
  await expect(db.exec(`SELECT public.review_applicant_identity('${employee}',false,'')`)).rejects.toThrow('Rejection reason required');
  await db.exec(`SELECT public.review_applicant_identity('${employee}',false,'Bild unscharf')`);
  expect(await active()).toBe(false);
  await db.exec(`SELECT set_config('test.uid','${employee}',false); SELECT public.submit_applicant_identity('${front}','${back}'); SELECT set_config('test.uid','${admin}',false); SELECT public.review_applicant_identity('${employee}',true,NULL)`);
  expect(await active()).toBe(true);
  await db.exec(`INSERT INTO public.tasks(assigned_to) VALUES('${employee}')`);
  await expect(db.exec(`UPDATE public.employee_documents SET content='Changed'`)).rejects.toThrow('Accepted contract is immutable');
  await db.exec(`SELECT set_config('test.uid','${employee}',false); SET ROLE authenticated;`);
  await expect(db.exec(`UPDATE public.profiles SET verified=true`)).rejects.toThrow('Admin status fields are protected');
  await expect(db.exec(`UPDATE public.employee_documents SET signature_data='forged'`)).rejects.toThrow('Use contract signing');
  await db.exec(`RESET ROLE; UPDATE public.applications SET status='rejected';`);
  expect(await active()).toBe(false);
  await db.close();
},30000);